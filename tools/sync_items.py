#!/usr/bin/env python3
"""Rebuilds data/items.yaml from the game's item catalogue.

The game is the source of truth for what exists and for every number: zone-server's items.yml for the
item itself, the client's items.csv for its name, fishing.yml and the mob files for where it comes from.
The docs only add what the game does not have: a reference `value` for the Bestia Blueprint Calculator,
an `icon`, a hand-written `description` and items that are designed but not built yet (`planned: true`).
Those keys survive a sync; every other key is rewritten.

Usage: python3 tools/sync_items.py [path/to/bestia-behemoth]
"""
import csv
import sys
from pathlib import Path

import yaml

DOCS = Path(__file__).resolve().parent.parent
ITEMS_YAML = DOCS / "data" / "items.yaml"

# Keys only the docs know. Everything else in an entry comes from the game.
DOCS_KEYS = ("value", "icon", "description")

HEADER = """\
# Every item of the Item Database page, and the loot the Bestia Blueprint Calculator can pick from.
#
# Generated by tools/sync_items.py from the game's items.yml. Edit only `value`, `icon`, `description` and
# items with `planned: true` here; the sync rewrites every other key. A `description` written here wins over
# the game's text.
#
# value is a reference price in coins, for pricing loot. Bread is 9 and a gold ore 10,000
# (money-supply.md). The sync estimates a missing value once, from the game's commodity price, the item's
# cheapest recipe or its level (see estimate_values); after that it is the docs' own and may be edited.
"""

STATION_SUFFIX = "_kit"
WEIGHT_UNITS_PER_KG = 100


def main():
    game = Path(sys.argv[1]) if len(sys.argv) > 1 else DOCS.parent / "bestia-behemoth"
    resources = game / "zone-server" / "src" / "main" / "resources"

    game_items = yaml.safe_load((resources / "items.yml").read_text())["items"]
    names = read_names(game / "bestia-client" / "src" / "Localization" / "items.csv")
    fish = {c["item"] for c in yaml.safe_load((resources / "fishing.yml").read_text())["catches"]}
    drops = read_mob_drops(resources / "mob")

    docs_items = {i["id"]: i for i in yaml.safe_load(ITEMS_YAML.read_text())}

    recipes = [r for name in ("recipes.yml", "gear_recipes.yml") for r in yaml.safe_load((resources / name).read_text())["recipes"]]
    commodities = yaml.safe_load((resources / "economy" / "economy.yml").read_text())["commodities"]

    synced = []
    for item in game_items:
        db_name = item["item-db-name"]
        entry = from_game(item, names.get(db_name.upper(), db_name), fish, drops)
        docs = docs_items.pop(db_name, {})
        entry.update({k: docs[k] for k in DOCS_KEYS if k in docs})
        entry.setdefault("description", item["description"])
        synced.append(entry)

    estimate_values(synced, recipes, {c["item"]: c["price"] for c in commodities})

    planned = []
    for docs in docs_items.values():
        if not docs.get("planned"):
            print(f"{docs['id']} left the game; kept as planned", file=sys.stderr)
        categories = [c for c in docs.get("categories", []) if c != "planned"]
        planned.append({**docs, "planned": True, "categories": categories + ["planned"]})

    ITEMS_YAML.write_text(HEADER + yaml.dump(synced + planned, Dumper=Dumper, sort_keys=False, allow_unicode=True,
                                             width=120))
    print(f"{len(synced)} game items, {len(planned)} planned", file=sys.stderr)


# A crafter sells above cost; the margin is the work. A recipe's base chance is not priced in: it is before the
# skill bonuses that a crafter who sells the item has.
CRAFT_MARGIN = 1.2

# What nothing makes and nobody prices: anchored on the docs' hand-set raw materials, about 3 coins at level 1 and
# 2,500 at level 100.
RAW_BASE = 3
RAW_GROWTH = 1.07


def estimate_values(entries, recipes, commodity_prices):
    """Fills a missing `value`. A game commodity price wins, then the cheapest recipe, then the item level."""
    by_id = {e["id"]: e for e in entries}
    known = {e["id"]: e["value"] for e in entries if e.get("value") is not None}
    known.update({k: v for k, v in commodity_prices.items() if k in by_id and k not in known})

    makes = {}
    for recipe in recipes:
        output = recipe.get("output")
        if output and output["item"] in by_id:
            makes.setdefault(output["item"], []).append(recipe)

    def crafted(item_id, visiting):
        costs = []
        for recipe in makes.get(item_id, []):
            inputs = [(i["item"], i["amount"]) for i in recipe["inputs"]]
            if any(i in visiting for i, _ in inputs):
                continue
            cost = sum(value_of(i, visiting | {item_id}) * amount for i, amount in inputs)
            costs.append(cost / recipe["output"]["amount"] * CRAFT_MARGIN)
        return min(costs) if costs else None

    def value_of(item_id, visiting=frozenset()):
        if item_id in known:
            return known[item_id]
        price = crafted(item_id, visiting)
        if price is None:
            price = RAW_BASE * RAW_GROWTH ** by_id[item_id]["item_level"]
        if not visiting:
            known[item_id] = price
        return price

    for entry in entries:
        if entry.get("value") is None:
            entry["value"] = max(1, round(value_of(entry["id"])))


def read_names(csv_path):
    with csv_path.open(newline="") as f:
        return {row["keys"]: row["en"] for row in csv.DictReader(f) if not row["keys"].endswith("_DESC")}


def read_mob_drops(mob_dir):
    drops = set()
    for path in mob_dir.rglob("*.yml"):
        mob = yaml.safe_load(path.read_text()) or {}
        drops |= {row["item"] for row in mob.get("loot") or []}
    return drops


def from_game(item, name, fish, drops):
    entry = {
        "id": item["item-db-name"],
        "name": name,
        "game_id": item["id"],
        "type": label(item["type"]),
        "categories": categories(item, fish, drops),
        "weight": round(item["weight"] / WEIGHT_UNITS_PER_KG, 2),
        "item_level": item["base-level"],
        "material": label(item["material"]),
    }
    optional = {
        "min_level": item.get("min-level"),
        "slot": label(item.get("equip-slot", "").replace("_1", "")),
        "weapon_type": label(item.get("weapon-type")),
        "armor_type": label(item.get("armor-type")),
        "ammo_type": label(item.get("ammo-type")),
        "two_handed": item.get("two-handed"),
        "range": item.get("attack-range"),
        "attack": item.get("attack"),
        "magic_attack": item.get("magic-attack"),
        "defense": item.get("defense"),
        "magic_defense": item.get("magic-defense"),
        "stats": item.get("stats"),
        "durability": item.get("max-durability"),
        "novice_only": item.get("novice-only"),
    }
    entry.update({k: v for k, v in optional.items() if v})
    return entry


def categories(item, fish, drops):
    db_name, kind, slot = item["item-db-name"], item["type"], item.get("equip-slot")
    found = []
    if kind == "EQUIP":
        if item.get("weapon-type"):
            found.append("weapon")
        elif slot == "ACCESSORY_1":
            found.append("accessory")
        elif slot == "LIGHT_SOURCE":
            found.append("light")
        else:
            found.append("armor")
    elif kind == "AMMO":
        found.append("ammo")
    elif db_name.endswith(STATION_SUFFIX):
        found.append("station")
    elif kind == "USABLE":
        found.append("consumable")
    else:
        found.append(material_category(item))
    if db_name in fish:
        found.append("fishing")
    if db_name in drops:
        found.append("drop")
    return found


def material_category(item):
    db_name = item["item-db-name"]
    if db_name.endswith("_ore"):
        return "ore"
    if db_name.endswith(("_ingot", "_bar")) or db_name == "quicksilver":
        return "metal"
    if db_name.startswith(("rough_", "cut_")) or db_name == "essence_gem":
        return "gem"
    if db_name.endswith("_herb") or db_name in ("deathcap", "thornvine", "glowcap"):
        return "herb"
    if item["material"] == "WOOD" and db_name != "coal":
        return "wood"
    return "material"


def label(enum_name):
    return enum_name.replace("_", " ").title() if enum_name else None


class Dumper(yaml.SafeDumper):
    pass


def represent_str(dumper, text):
    style = "|" if "\n" in text else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", text, style=style)


def represent_dict(dumper, data):
    # Stats and categories read best on one line.
    flow = all(not isinstance(v, (dict, list)) for v in data.values()) and len(data) <= 6 and "id" not in data
    return dumper.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)


def represent_list(dumper, data):
    flow = all(isinstance(v, str) for v in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


Dumper.add_representer(str, represent_str)
Dumper.add_representer(dict, represent_dict)
Dumper.add_representer(list, represent_list)

if __name__ == "__main__":
    main()
